#!/bin/bash
set -e

cmd="$1"
app="rjv"

if test ! "$cmd"; then
    echo "command required."
    echo
    echo "available commands:"
    # alphabetical order
    echo "  build               build project"
    echo "  build.all           build project, ignore cache"
    echo "  build.release       build project for distribution"
    echo "  clean               deletes all generated files"
    exit 1
fi

shift
rest=$*

if test "$cmd" = "build"; then
    ./manage.sh clean
    # CGO_ENABLED=0 skips CGO and linking against glibc to build static binaries.
    # -v 'verbose'
    CGO_ENABLED=0 go build \
        -v
    echo "wrote $app"
    exit 0

elif test "$cmd" = "build.all"; then
    # CGO_ENABLED=0 skips CGO and linking against glibc to build static binaries.
    # -a 'build all'
    # -v 'verbose'
    ./manage.sh clean
    CGO_ENABLED=0 go build \
        -a \
        -v
    exit 0

elif test "$cmd" = "build.release"; then
    # GOOS is 'Go OS' and is being explicit in which OS to build for.
    # CGO_ENABLED=0 skips CGO and linking against glibc to build static binaries.
    # ld -s is 'disable symbol table'
    # ld -w is 'disable DWARF generation'
    # -trimpath removes leading paths to source files
    # -v 'verbose'
    # -o 'output'
    set -u
    version="$1" # '1.0.0'

    platforms=("linux" "darwin" "windows")
    architectures=("amd64" "arm64")
    unsupported_upx=("darwin-arm64" "darwin-amd64" "windows-arm64")

    for os in "${platforms[@]}"; do
        for arch in "${architectures[@]}"; do
            target_name="${os}-${arch}"

            output_name="$target_name"
            if [ "$os" = "windows" ]; then
                output_name+=".exe"
            fi

            echo "Building $os/$arch..."
            GOOS=$os GOARCH=$arch CGO_ENABLED=0 go build \
                -ldflags "-s -w -X main.APP_VERSION=$version" \
                -trimpath \
                -v \
                -o "$output_name"

            # upx compression, skipped for the targets upx cannot handle
            should_skip_upx=false
            for unsupported in "${unsupported_upx[@]}"; do
                if [[ "$target_name" == "$unsupported" ]]; then
                    should_skip_upx=true
                    break
                fi
            done

            if ! $should_skip_upx; then
                upx "$output_name"
            fi

            sha256sum "$output_name" > "$output_name.sha256"
        done
    done

    echo "done"
    exit 0

elif test "$cmd" = "clean"; then
    tbd=("main" "$app") # generated by 'build'

    # generated by 'build.release'
    for os in "linux" "darwin" "windows"; do
        for arch in "amd64" "arm64"; do
            output_name="${os}-${arch}"
            if [ "$os" = "windows" ]; then
                output_name+=".exe"
            fi
            tbd+=("$output_name" "$output_name.sha256")
        done
    done

    # -f 'force' don't fail if file doesn't exist.
    # -v 'verbose' print the name of the file that was deleted.
    rm -fv "${tbd[@]}"
    exit 0

fi

echo "unknown command: $cmd"
exit 1
